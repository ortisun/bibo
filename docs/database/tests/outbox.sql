-- Suite: outbox
-- Proves ADR 0004 at the database level: a state change, its ledger entry and its event commit together
-- or not at all (invariant INV-03); an event names a real transition and cannot be emitted twice for one
-- aggregate version; an event is a fact that cannot be edited; and a consumer's inbox makes a repeated
-- delivery harmless.

DO $$
BEGIN
  PERFORM dbtest.mk_tenant(1);
  PERFORM dbtest.mk_tenant(2);
  PERFORM dbtest.mk_job(1, 1);
  PERFORM dbtest.mk_job(1, 2);
  PERFORM dbtest.mk_job(2, 1);
  PERFORM dbtest.mk_stage_run(1, 1, 1);
  PERFORM dbtest.mk_stage_run(1, 2, 2);
  -- Aggregates must have reached the version an event announces: job 1101 at version 2, stage run 1201 at 2.
  PERFORM dbtest.set_status('jobs', 1, dbtest.u(1101), 'ACTIVE');
  PERFORM dbtest.set_status('stage_runs', 1, dbtest.u(1201), 'READY');
END
$$;

-- An event for job 1101, as the engine writes it. Overrides keep each test to one broken thing.
CREATE FUNCTION dbtest.event_sql(
  p_event uuid, p_type text DEFAULT 'job.admitted', p_agg_type text DEFAULT 'job', p_agg uuid DEFAULT dbtest.u(1101),
  p_version bigint DEFAULT 2, p_transition text DEFAULT 'J01', p_payload text DEFAULT '{"issue_number": 12}', p_tenant uuid DEFAULT dbtest.u(1),
  p_job uuid DEFAULT dbtest.u(1101), p_extra_cols text DEFAULT '', p_extra_vals text DEFAULT ''
) RETURNS text LANGUAGE sql AS $$
  SELECT format($q$INSERT INTO outbox (tenant_id, event_id, event_type, job_id, aggregate_type, aggregate_id, aggregate_version, transition_id,
                       correlation_id, occurred_at, producer, payload %s)
                   VALUES (%L, %L, %L, %L, %L, %L, %s, %L, %L, now(), 'workflow.engine', %L::jsonb %s)$q$,
                p_extra_cols, p_tenant, p_event, p_type, p_job, p_agg_type, p_agg, p_version, p_transition, dbtest.u(1500), p_payload, p_extra_vals)
$$;

-- ---------------------------------------------------------------------------------------------
-- 1. The application role writes events; the database numbers them for the relay.

DO $$
BEGIN
  PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(1)), 'factory_app');
  PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(2), 'stage_run.ready', 'stage_run', dbtest.u(1201), 2, 'S01'), 'factory_app');
  PERFORM dbtest.expect_eq('two events were written, and the application role needed no sequence privilege for seq', (SELECT count(*) FROM outbox), 2::bigint);
  PERFORM dbtest.expect_true('seq rises with each event', (SELECT max(seq) > min(seq) FROM outbox));
  PERFORM dbtest.expect_error('seq is generated by the database: a supplied value is refused',
    dbtest.event_sql(dbtest.u(3), p_version => 3, p_extra_cols => ', seq', p_extra_vals => ', 42'), '428C9', 'factory_app');
  PERFORM dbtest.expect_true('a new event starts unpublished with zero attempts',
    (SELECT bool_and(published_at IS NULL AND publish_attempts = 0) FROM outbox));
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 2. An event names a real transition of the right machine, and says what that transition emits.

DO $$
BEGIN
  -- Harmless edits that only raise the job's version, so versions 3 to 5 have been reached.
  UPDATE jobs SET policy_hash = NULL, version = version + 1 WHERE id = dbtest.u(1101);
  UPDATE jobs SET policy_hash = NULL, version = version + 1 WHERE id = dbtest.u(1101);
  UPDATE jobs SET policy_hash = NULL, version = version + 1 WHERE id = dbtest.u(1101);
  PERFORM dbtest.expect_error('an event type that the named transition does not emit is refused (job.rejected under J01)',
    dbtest.event_sql(dbtest.u(10), 'job.rejected', p_version => 3), '23503', 'factory_app');
  PERFORM dbtest.expect_error('a transition that does not exist is refused',
    dbtest.event_sql(dbtest.u(11), p_transition => 'J99', p_version => 3), '23503', 'factory_app');
  PERFORM dbtest.expect_error('a transition of another machine is refused (S01 under an aggregate of type job)',
    dbtest.event_sql(dbtest.u(12), p_transition => 'S01', p_version => 3), '23503', 'factory_app');
  PERFORM dbtest.expect_error('an event whose type does not start with its aggregate type is refused',
    dbtest.event_sql(dbtest.u(13), 'stage_run.ready', 'job', p_transition => 'S01', p_version => 3), '23514', 'factory_app', 'outbox_event_type_matches_aggregate');
  PERFORM dbtest.expect_error('a heartbeat is not a domain event',
    dbtest.event_sql(dbtest.u(14), 'attempt.heartbeat', 'attempt', dbtest.u(1301), 3, 'A03'), '23514', 'factory_app', 'outbox_event_type_check');
  PERFORM dbtest.expect_error('an event with a malformed type is refused',
    dbtest.event_sql(dbtest.u(15), 'JobAdmitted', p_version => 3), '23514', 'factory_app', 'outbox_event_type_check');
  PERFORM dbtest.expect_error('an unknown aggregate type is refused',
    dbtest.event_sql(dbtest.u(16), 'sandbox.created', 'sandbox', p_version => 3), '23514', 'factory_app', 'outbox_aggregate_type_check');
  PERFORM dbtest.expect_error('an aggregate version below 1 is refused',
    dbtest.event_sql(dbtest.u(17), p_version => 0), '23514', 'factory_app', 'outbox_aggregate_version_check');
  PERFORM dbtest.expect_error('a malformed traceparent is refused',
    dbtest.event_sql(dbtest.u(18), p_version => 3, p_extra_cols => ', traceparent', p_extra_vals => ', ''not-a-traceparent'''), '23514', 'factory_app', 'outbox_traceparent_check');
  PERFORM dbtest.expect_error('a payload that is not an object is refused',
    dbtest.event_sql(dbtest.u(19), p_version => 3, p_payload => '[1, 2]'), '23514', 'factory_app', 'outbox_payload_check');
  PERFORM dbtest.expect_error('a payload larger than 16 KiB is refused (large content belongs in the artifact store)',
    dbtest.event_sql(dbtest.u(20), p_version => 3, p_payload => json_build_object('blob', repeat('x', 17000))::text), '23514', 'factory_app', 'outbox_payload_check');
  PERFORM dbtest.expect_error('a payload schema name without a version is refused',
    dbtest.event_sql(dbtest.u(21), p_version => 3, p_extra_cols => ', payload_schema_name', p_extra_vals => ', ''stage-run-passed'''), '23514', 'factory_app', 'outbox_payload_schema_check');
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 3. One event per aggregate version. A replayed transition cannot emit twice.

DO $$
BEGIN
  PERFORM dbtest.expect_error('a second event for the same aggregate version is refused',
    dbtest.event_sql(dbtest.u(30)), '23505', 'factory_app', 'outbox_one_event_per_aggregate_version');
  PERFORM dbtest.expect_error('the same event id twice in one tenant is refused',
    dbtest.event_sql(dbtest.u(1), p_version => 5), '23505', 'factory_app', 'outbox_pkey');
  PERFORM dbtest.expect_error('an event for a job that does not exist is refused',
    dbtest.event_sql(dbtest.u(31), p_version => 5, p_job => dbtest.u(99999)), '23503', 'factory_app');
END
$$;

-- The aggregate an event names must exist in the tenant, belong to the job, and have reached the version.
-- The check runs at commit; SET CONSTRAINTS IMMEDIATE makes it answer inside the statement.
DO $$
DECLARE
  imm text := 'SET CONSTRAINTS outbox_aggregate_check IMMEDIATE; ';
BEGIN
  UPDATE stage_runs SET max_attempts = max_attempts, version = version + 1 WHERE id = dbtest.u(1201);   -- version 3
  PERFORM dbtest.expect_ok('an event for a stage run that has reached version 3 passes the aggregate check',
    imm || dbtest.event_sql(dbtest.u(60), 'stage_run.passed', 'stage_run', dbtest.u(1201), 3, 'S08'), 'factory_app');
  PERFORM dbtest.expect_error('an event for an aggregate that does not exist is refused',
    imm || dbtest.event_sql(dbtest.u(61), p_agg => dbtest.u(77777), p_version => 2), '23514', 'factory_app', 'outbox_aggregate_exists');
  PERFORM dbtest.expect_error('an event for an aggregate of another tenant is refused (the tenant is part of the lookup)',
    imm || dbtest.event_sql(dbtest.u(62), p_agg => dbtest.u(2101), p_version => 2), '23514', 'factory_app', 'outbox_aggregate_exists');
  PERFORM dbtest.expect_error('an event whose aggregate belongs to another job is refused',
    imm || dbtest.event_sql(dbtest.u(63), 'stage_run.passed', 'stage_run', dbtest.u(1201), 3, 'S08', p_job => dbtest.u(1102)), '23514', 'factory_app', 'outbox_aggregate_belongs_to_job');
  PERFORM dbtest.expect_error('an event that announces a version the aggregate has not reached is refused',
    imm || dbtest.event_sql(dbtest.u(64), 'stage_run.passed', 'stage_run', dbtest.u(1201), 9, 'S08'), '23514', 'factory_app', 'outbox_aggregate_has_reached_version');
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 4. An event is a fact. Only the relay's bookkeeping changes: published_at once, publish_attempts up.

DO $$
DECLARE
  e uuid := dbtest.u(1);
BEGIN
  PERFORM dbtest.expect_error('the application role cannot rewrite a payload (no column grant)',
    format($q$UPDATE outbox SET payload = '{}' WHERE event_id = %L$q$, e), '42501', 'factory_app');
  PERFORM dbtest.expect_error('the application role cannot rewrite the event type', format($q$UPDATE outbox SET event_type = 'job.failed' WHERE event_id = %L$q$, e), '42501', 'factory_app');
  PERFORM dbtest.expect_error('the application role cannot delete events', 'DELETE FROM outbox', '42501', 'factory_app');
  PERFORM dbtest.expect_error('the application role cannot truncate the outbox', 'TRUNCATE outbox', '42501', 'factory_app');
  PERFORM dbtest.expect_error('the owner cannot rewrite a payload either (trigger)',
    format($q$UPDATE outbox SET payload = '{"tampered": true}' WHERE event_id = %L$q$, e), '23514', NULL, 'outbox_event_is_immutable');
  PERFORM dbtest.expect_error('the owner cannot move an event to another job (trigger)',
    format($q$UPDATE outbox SET aggregate_version = 9 WHERE event_id = %L$q$, e), '23514', NULL, 'outbox_event_is_immutable');

  -- The relay runs as the system role (ADR 0012): it reads events of every tenant and marks them published.
  PERFORM dbtest.exec(format($q$UPDATE outbox SET published_at = now(), publish_attempts = publish_attempts + 1 WHERE event_id = %L$q$, e), 'factory_system');
  PERFORM dbtest.expect_true('the relay, running as the system role, marked the event published', (SELECT published_at IS NOT NULL AND publish_attempts = 1 FROM outbox WHERE event_id = e));
  PERFORM dbtest.expect_error('the system role cannot rewrite a payload either (no column grant)',
    format($q$UPDATE outbox SET payload = '{}' WHERE event_id = %L$q$, dbtest.u(2)), '42501', 'factory_system');
  PERFORM dbtest.expect_error('the system role cannot delete events', 'DELETE FROM outbox', '42501', 'factory_system');
  PERFORM dbtest.expect_error('a published event cannot be marked published again at another time',
    format($q$UPDATE outbox SET published_at = now() + interval '1 second' WHERE event_id = %L$q$, e), '23514', 'factory_app', 'outbox_event_is_immutable');
  PERFORM dbtest.expect_error('a published event cannot be marked unpublished',
    format($q$UPDATE outbox SET published_at = NULL WHERE event_id = %L$q$, e), '23514', 'factory_app', 'outbox_event_is_immutable');
  PERFORM dbtest.expect_error('publish_attempts cannot go down',
    format($q$UPDATE outbox SET publish_attempts = 0 WHERE event_id = %L$q$, e), '23514', 'factory_app', 'outbox_event_is_immutable');
  PERFORM dbtest.expect_ok('publish_attempts can go up (a retry after a failed publish)',
    format($q$UPDATE outbox SET publish_attempts = publish_attempts + 1 WHERE event_id = %L$q$, dbtest.u(2)), 'factory_app');
END
$$;

-- The relay's own query works with the grants it has: unpublished rows in order, skipping locked ones.
DO $$
BEGIN
  PERFORM dbtest.expect_ok('the relay query (FOR UPDATE SKIP LOCKED over unpublished rows) runs as the system role',
    'SELECT event_id FROM outbox WHERE published_at IS NULL ORDER BY seq LIMIT 100 FOR UPDATE SKIP LOCKED', 'factory_system');
  -- Tenant 2 has an unpublished event too.
  PERFORM dbtest.set_status('jobs', 2, dbtest.u(2101), 'ACTIVE');
  PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(70), p_agg => dbtest.u(2101), p_tenant => dbtest.u(2), p_job => dbtest.u(2101)));
  PERFORM dbtest.expect_eq('the relay sees the unpublished events of every tenant, the application role only its own',
    dbtest.run_as('SELECT event_id FROM outbox WHERE published_at IS NULL', 'factory_system') || ' / ' || dbtest.run_as('SELECT event_id FROM outbox WHERE published_at IS NULL', 'factory_app', 1),
    'rows=2 / rows=1');
  PERFORM dbtest.expect_eq('only the second event of tenant 1 and the event of tenant 2 are still unpublished', (SELECT count(*) FROM outbox WHERE published_at IS NULL), 2::bigint);
END
$$;

-- A rolled back insert leaves a hole in seq, so consumers must order by aggregate_version (ADR 0004).
DO $$
DECLARE
  before_seq bigint := (SELECT max(seq) FROM outbox);
  after_seq bigint;
BEGIN
  BEGIN
    PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(40), p_version => 3));
    RAISE EXCEPTION 'abandon' USING ERRCODE = 'XX998';
  EXCEPTION WHEN SQLSTATE 'XX998' THEN NULL;
  END;
  PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(41), p_version => 3));
  after_seq := (SELECT max(seq) FROM outbox);
  PERFORM dbtest.expect_true('seq has a gap after a rollback (so ordering by seq alone is wrong)', after_seq - before_seq >= 2);
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 5. Atomicity (INV-03). One decision writes the status change, the ledger entry and the event. The
-- three are written in a subtransaction here; a failure anywhere rolls all of them back.

DO $$
DECLARE
  -- Job 1102 is RECEIVED at version 1: admitting it (J01) is the decision, announced as job version 2.
  status0 text := (SELECT status FROM jobs WHERE id = dbtest.u(1102));
  version0 bigint := (SELECT version FROM jobs WHERE id = dbtest.u(1102));
  ledger0 bigint := (SELECT count(*) FROM ledger_entries);
  outbox0 bigint := (SELECT count(*) FROM outbox);
  imm text := 'SET CONSTRAINTS outbox_aggregate_check IMMEDIATE; ';
BEGIN
  -- (a) A failure after the outbox insert: nothing remains.
  BEGIN
    UPDATE jobs SET status = 'ACTIVE', version = version + 1 WHERE id = dbtest.u(1102);
    PERFORM dbtest.append_entry(1, dbtest.u(1102), dbtest.u(1202), 1);
    PERFORM dbtest.exec(imm || dbtest.event_sql(dbtest.u(50), p_agg => dbtest.u(1102), p_job => dbtest.u(1102), p_version => version0 + 1));
    RAISE EXCEPTION 'injected fault after the outbox insert' USING ERRCODE = 'XX997';
  EXCEPTION WHEN SQLSTATE 'XX997' THEN NULL;
  END;
  PERFORM dbtest.expect_true('a fault after the outbox insert rolls back the status change, the ledger entry and the event together',
    (SELECT status = status0 AND version = version0 FROM jobs WHERE id = dbtest.u(1102))
    AND (SELECT count(*) FROM ledger_entries) = ledger0 AND (SELECT count(*) FROM outbox) = outbox0);

  -- (b) The event is refused by the database (it names a transition that does not emit that type):
  -- the earlier writes in the same decision go with it.
  BEGIN
    UPDATE jobs SET status = 'ACTIVE', version = version + 1 WHERE id = dbtest.u(1102);
    PERFORM dbtest.append_entry(1, dbtest.u(1102), dbtest.u(1202), 1);
    PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(51), 'job.failed', p_agg => dbtest.u(1102), p_job => dbtest.u(1102), p_version => version0 + 1));
  EXCEPTION WHEN foreign_key_violation THEN NULL;
  END;
  PERFORM dbtest.expect_true('an event the database refuses takes the status change and the ledger entry with it',
    (SELECT status = status0 AND version = version0 FROM jobs WHERE id = dbtest.u(1102))
    AND (SELECT count(*) FROM ledger_entries) = ledger0 AND (SELECT count(*) FROM outbox) = outbox0);

  -- (c) A fault before the outbox insert (a bad ledger entry): no state change and no event.
  BEGIN
    UPDATE jobs SET status = 'ACTIVE', version = version + 1 WHERE id = dbtest.u(1102);
    PERFORM dbtest.insert_entry(1, dbtest.u(1102), dbtest.u(1202), 1, NULL, p_hash => dbtest.sha('wrong'));
    PERFORM dbtest.exec(dbtest.event_sql(dbtest.u(52), p_agg => dbtest.u(1102), p_job => dbtest.u(1102), p_version => version0 + 1));
  EXCEPTION WHEN check_violation THEN NULL;
  END;
  PERFORM dbtest.expect_true('a fault before the outbox insert leaves no state change and no event',
    (SELECT status = status0 AND version = version0 FROM jobs WHERE id = dbtest.u(1102))
    AND (SELECT count(*) FROM ledger_entries) = ledger0 AND (SELECT count(*) FROM outbox) = outbox0);

  -- (d) Without a fault all three are there.
  UPDATE jobs SET status = 'ACTIVE', version = version + 1 WHERE id = dbtest.u(1102);
  PERFORM dbtest.append_entry(1, dbtest.u(1102), dbtest.u(1202), 1);
  PERFORM dbtest.exec(imm || dbtest.event_sql(dbtest.u(53), p_agg => dbtest.u(1102), p_job => dbtest.u(1102), p_version => version0 + 1));
  PERFORM dbtest.expect_true('without a fault the status change, the ledger entry and the event are all there',
    (SELECT status = 'ACTIVE' FROM jobs WHERE id = dbtest.u(1102))
    AND (SELECT count(*) FROM ledger_entries) = ledger0 + 1 AND (SELECT count(*) FROM outbox) = outbox0 + 1);
END
$$;

-- ---------------------------------------------------------------------------------------------
-- 6. Consumer idempotency. The inbox row and the consumer's effect inside PostgreSQL commit together;
-- a repeated delivery of the same event hits the primary key and is dropped.

CREATE TABLE dbtest.effects (consumer text, event_id uuid);

CREATE FUNCTION dbtest.consume(p_consumer text, p_event uuid) RETURNS boolean LANGUAGE plpgsql AS $$
DECLARE
  first_time uuid;
BEGIN
  INSERT INTO inbox (tenant_id, consumer, event_id) VALUES (dbtest.u(1), p_consumer, p_event)
  ON CONFLICT DO NOTHING RETURNING event_id INTO first_time;
  IF first_time IS NULL THEN
    RETURN false;
  END IF;
  INSERT INTO dbtest.effects VALUES (p_consumer, p_event);   -- the effect, in the same transaction
  RETURN true;
END
$$;

DO $$
DECLARE
  i int;
  applied int := 0;
BEGIN
  FOR i IN 1..10 LOOP
    IF dbtest.consume('dashboard', dbtest.u(1)) THEN applied := applied + 1; END IF;
  END LOOP;
  PERFORM dbtest.expect_eq('ten deliveries of one event give one effect for the consumer', applied, 1);
  PERFORM dbtest.expect_true('another consumer of the same event applies its own effect once',
    dbtest.consume('notifier', dbtest.u(1)) AND NOT dbtest.consume('notifier', dbtest.u(1)));
  PERFORM dbtest.expect_error('a raw duplicate inbox row violates the primary key',
    format($q$INSERT INTO inbox (tenant_id, consumer, event_id) VALUES (%L, 'dashboard', %L)$q$, dbtest.u(1), dbtest.u(1)), '23505', 'factory_app', 'inbox_pkey');
  PERFORM dbtest.expect_ok('the same event id is a different row for the same consumer in another tenant',
    format($q$INSERT INTO inbox (tenant_id, consumer, event_id) VALUES (%L, 'dashboard', %L)$q$, dbtest.u(2), dbtest.u(1)), 'factory_app', 2);
  PERFORM dbtest.expect_error('an inbox row is a record: the application role cannot update it',
    'UPDATE inbox SET processed_at = now()', '42501', 'factory_app');
  PERFORM dbtest.expect_error('an inbox row is a record: the application role cannot delete it',
    'DELETE FROM inbox', '42501', 'factory_app');
  PERFORM dbtest.expect_error('a consumer name that is not a slug is refused',
    format($q$INSERT INTO inbox (tenant_id, consumer, event_id) VALUES (%L, 'Bad Name', %L)$q$, dbtest.u(1), dbtest.u(5)), '23514', 'factory_app');
END
$$;
