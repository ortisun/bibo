#!/usr/bin/env python3
"""Helpers of scripts/worker-host.sh (ADR 0036). Run it through the script, not by hand.

    worker_host.py forbidden SECURITY_YAML PATH...
        Prints each PATH that is, or lies under, a forbidden mount source of the sandbox policy
        (sandbox.forbidden_mount_sources), one per line, by the rule of SandboxSpec::validate: a
        listed source forbids itself and everything under it, and "/" forbids only itself.
        Exit 0 whether or not a path is printed; 2 on misuse.

    worker_host.py render TEMPLATE OUT [--credentials FILE] NAME=VALUE...
        Fills each @NAME@ of TEMPLATE, merges FILE over the result (a mapping merges key by key, any
        other value replaces), and writes OUT with mode 0600. A placeholder left unfilled, a NAME the
        template does not use, or a credentials file that is not a mapping is an error (exit 1). The
        values are never printed.

    worker_host.py image CATALOG PLATFORM ROLE
        Prints the pinned reference of an image of infra/sandbox-images/images.json.

Needs PyYAML (the script runs it with `uv run --with pyyaml==6.0.3`).
"""
import json
import os
import re
import sys

import yaml

PLACEHOLDER = re.compile(r"@([A-Z_]+)@")


def forbidden(security_yaml, paths):
    with open(security_yaml, encoding="utf-8") as handle:
        policy = yaml.safe_load(handle)
    listed = policy["sandbox"]["forbidden_mount_sources"]
    def under(path, source):
        return path == source or (source != "/" and path.startswith(source.rstrip("/") + "/"))

    for path in paths:
        # Both the path as written and the path it resolves to: a link must not lead out of a forbidden source
        # (the daemon mounts what the path resolves to), and a forbidden name must not pass because the system
        # resolves it elsewhere (/home is a link on macOS).
        spellings = [os.path.normpath(path), os.path.realpath(path)]
        hit = next(((spelled, source) for spelled in spellings for source in listed if under(spelled, source)), None)
        if hit:
            print(f"{path} (as {hit[0]}, under {hit[1]})")


def merge(base, extra):
    if isinstance(base, dict) and isinstance(extra, dict):
        merged = dict(base)
        for key, value in extra.items():
            merged[key] = merge(base[key], value) if key in base else value
        return merged
    return extra


def render(template, out, credentials, pairs):
    values = {}
    for pair in pairs:
        name, sep, value = pair.partition("=")
        if not sep or not re.fullmatch(r"[A-Z_]+", name):
            sys.exit(f"worker_host.py: '{name}' is not NAME=VALUE")
        values[name] = value
    with open(template, encoding="utf-8") as handle:
        text = handle.read()
    body = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
    used = set(PLACEHOLDER.findall(body))
    missing, unused = sorted(used - values.keys()), sorted(values.keys() - used)
    if missing or unused:
        sys.exit(f"worker_host.py: the template needs {missing or 'nothing more'} and does not use {unused or 'nothing else'}")
    config = yaml.safe_load(PLACEHOLDER.sub(lambda m: values[m.group(1)], body))
    if credentials:
        with open(credentials, encoding="utf-8") as handle:
            extra = yaml.safe_load(handle)
        if extra is None:
            extra = {}
        if not isinstance(extra, dict):
            sys.exit(f"worker_host.py: {credentials} must hold a mapping of configuration keys")
        config = merge(config, extra)
    header = (
        "# Generated by scripts/worker-host.sh from infra/compose/config/worker.host.example.yaml"
        + (" and credentials.yaml" if credentials else "")
        + ".\n# Written again on every start: change the template or credentials.yaml, not this file.\n"
    )
    descriptor = os.open(out + ".tmp", os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(header)
        yaml.safe_dump(config, handle, sort_keys=False, default_flow_style=False)
    os.chmod(out + ".tmp", 0o600)
    os.replace(out + ".tmp", out)


def image(catalog, platform, role):
    with open(catalog, encoding="utf-8") as handle:
        print(json.load(handle)["platforms"][platform]["images"][role]["reference"])


def main(argv):
    if len(argv) >= 3 and argv[1] == "forbidden":
        forbidden(argv[2], argv[3:])
    elif len(argv) >= 4 and argv[1] == "render":
        rest, credentials = argv[4:], None
        if rest[:1] == ["--credentials"]:
            if len(rest) < 2:
                sys.exit("worker_host.py: --credentials needs a file")
            credentials, rest = rest[1], rest[2:]
        render(argv[2], argv[3], credentials, rest)
    elif len(argv) == 5 and argv[1] == "image":
        image(argv[2], argv[3], argv[4])
    else:
        sys.stderr.write(__doc__ or "")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
