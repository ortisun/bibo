#!/usr/bin/env python3
"""Writes crates/domain/tests/support/example_index.rs.

The domain crate may not read files (its clippy.toml bans it, and its tests are linted with the
same file), so the tests embed every schema and every example with `include_str!`. This script
lists them. Run it again whenever a file is added to or removed from schemas/ or schemas/examples/.

    python3 -I crates/domain/tests/tools/gen_example_index.py            # rewrite the index
    python3 -I crates/domain/tests/tools/gen_example_index.py --check    # fail if it is stale

YAML examples cannot be read here because the domain crate has no YAML parser. Each one is covered
by a JSON transcription in tests/fixtures/yaml_transcriptions/<schema>--<name>.json. The script
fails if a YAML example has no transcription. The `contracts` crate owns the YAML parser and must
test the YAML files themselves.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CRATE_TESTS = os.path.dirname(HERE)
REPO = os.path.abspath(os.path.join(CRATE_TESTS, '..', '..', '..'))
SCHEMAS = os.path.join(REPO, 'schemas')
EXAMPLES = os.path.join(SCHEMAS, 'examples')
TRANSCRIPTIONS = os.path.join(CRATE_TESTS, 'fixtures', 'yaml_transcriptions')
OUTPUT = os.path.join(CRATE_TESTS, 'support', 'example_index.rs')

# include_str! paths are relative to the generated file, which is in tests/support/.
UP_TO_REPO = '../../../../'
UP_TO_TESTS = '../'


def rust_str(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def build():
    schemas = sorted(f[: -len('.schema.json')] for f in os.listdir(SCHEMAS) if f.endswith('.schema.json'))
    lines = [
        '// @generated by tests/tools/gen_example_index.py. Do not edit by hand.',
        '//',
        '// Every schema and every example is embedded at compile time, because the domain crate',
        '// does no file I/O. Re-run the script when a schema or an example is added or removed.',
        '',
        '/// One example document.',
        '#[derive(Debug, Clone, Copy)]',
        'pub struct Example {',
        '    /// The schema name, such as `gate-report`.',
        '    pub schema: &\'static str,',
        '    /// True under `valid/`, false under `invalid/`.',
        '    pub valid: bool,',
        '    /// The file name in the schemas folder.',
        '    pub file: &\'static str,',
        '    /// The document. For a YAML example this is its JSON transcription.',
        '    pub text: &\'static str,',
        '    /// For an invalid example, the validator message its `.expect` file names.',
        '    pub expect: &\'static str,',
        '}',
        '',
        '/// Every schema file: its name and its text.',
        '#[rustfmt::skip]',
        'pub const SCHEMAS: &[(&str, &str)] = &[',
    ]
    for name in schemas:
        lines.append(f'    ({rust_str(name)}, include_str!({rust_str(UP_TO_REPO + "schemas/" + name + ".schema.json")})),')
    lines.append('];')
    lines.append('')
    lines.append('/// Every example, valid ones first within each schema.')
    lines.append('#[rustfmt::skip]')
    lines.append('pub const EXAMPLES: &[Example] = &[')
    for name in schemas:
        for kind in ('valid', 'invalid'):
            folder = os.path.join(EXAMPLES, name, kind)
            if not os.path.isdir(folder):
                continue
            for file in sorted(os.listdir(folder)):
                if file.endswith('.expect'):
                    continue
                path = os.path.join(folder, file)
                if file.endswith('.json'):
                    text_path = UP_TO_REPO + f'schemas/examples/{name}/{kind}/{file}'
                elif file.endswith('.yaml') and kind == 'valid':
                    stem = file[: -len('.yaml')]
                    transcription = os.path.join(TRANSCRIPTIONS, f'{name}--{stem}.json')
                    if not os.path.isfile(transcription):
                        sys.exit(f'{path} is YAML and has no transcription at {transcription}')
                    text_path = UP_TO_TESTS + f'fixtures/yaml_transcriptions/{name}--{stem}.json'
                else:
                    sys.exit(f'unexpected example file: {path}')
                if kind == 'invalid':
                    expect_path = UP_TO_REPO + f'schemas/examples/{name}/{kind}/{file[:-len(".json")]}.expect'
                    expect = f'include_str!({rust_str(expect_path)})'
                else:
                    expect = '""'
                lines.append('    Example {')
                lines.append(f'        schema: {rust_str(name)},')
                lines.append(f'        valid: {"true" if kind == "valid" else "false"},')
                lines.append(f'        file: {rust_str(file)},')
                lines.append(f'        text: include_str!({rust_str(text_path)}),')
                lines.append(f'        expect: {expect},')
                lines.append('    },')
    lines.append('];')
    lines.append('')
    return '\n'.join(lines)


def main():
    text = build()
    if '--check' in sys.argv:
        current = open(OUTPUT).read() if os.path.exists(OUTPUT) else ''
        if current != text:
            sys.exit('example_index.rs is stale: run gen_example_index.py and commit the result')
        print('example_index.rs is up to date')
        return
    with open(OUTPUT, 'w') as handle:
        handle.write(text)
    print(f'wrote {OUTPUT}')


if __name__ == '__main__':
    main()
