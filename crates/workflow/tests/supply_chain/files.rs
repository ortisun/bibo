//! Builders for the dependency files of a base commit and a candidate.

use factory_workflow::gates::supply_chain::cargo::CargoFormat;
use factory_workflow::gates::supply_chain::integrity::{Context, Integrity, inspect};
use factory_workflow::gates::supply_chain::model::Side;
use factory_workflow::gates::supply_chain::names::PopularNames;

pub const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";

/// A 64-digit checksum made of one repeated digit, so a test reads it at a glance.
pub fn sum(digit: char) -> String {
    digit.to_string().repeat(64)
}

/// One `[[package]]` entry.
#[derive(Clone)]
pub struct Pkg {
    pub name: &'static str,
    pub version: &'static str,
    pub source: Option<String>,
    pub checksum: Option<String>,
    pub deps: Vec<&'static str>,
}

/// A package from the default registry with a checksum.
pub fn reg(name: &'static str, version: &'static str, digit: char) -> Pkg {
    Pkg {
        name,
        version,
        source: Some(CRATES_IO.to_owned()),
        checksum: Some(sum(digit)),
        deps: Vec::new(),
    }
}

/// The project itself: no source.
pub fn member(name: &'static str, deps: &[&'static str]) -> Pkg {
    Pkg {
        name,
        version: "0.1.0",
        source: None,
        checksum: None,
        deps: deps.to_vec(),
    }
}

impl Pkg {
    pub fn with_deps(mut self, deps: &[&'static str]) -> Self {
        self.deps = deps.to_vec();
        self
    }

    pub fn at_source(mut self, source: &str) -> Self {
        self.source = Some(source.to_owned());
        self
    }

    pub fn without_checksum(mut self) -> Self {
        self.checksum = None;
        self
    }
}

/// The text of a `Cargo.lock`.
pub fn lock(packages: &[Pkg]) -> String {
    let mut text = String::from("# This file is automatically @generated by Cargo.\nversion = 4\n");
    for package in packages {
        text.push_str(&format!(
            "\n[[package]]\nname = \"{}\"\nversion = \"{}\"\n",
            package.name, package.version
        ));
        if let Some(source) = &package.source {
            text.push_str(&format!("source = \"{source}\"\n"));
        }
        if let Some(checksum) = &package.checksum {
            text.push_str(&format!("checksum = \"{checksum}\"\n"));
        }
        if !package.deps.is_empty() {
            text.push_str("dependencies = [\n");
            for dep in &package.deps {
                text.push_str(&format!(" \"{dep}\",\n"));
            }
            text.push_str("]\n");
        }
    }
    text
}

/// The text of a `Cargo.toml` with the given extra body after `[package]`.
pub fn manifest(name: &str, body: &str) -> String {
    format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n{body}")
}

/// Files of one commit, as the stage hands them over.
pub fn files(list: &[(&str, String)]) -> Vec<(String, String)> {
    list.iter()
        .map(|(path, text)| ((*path).to_owned(), text.clone()))
        .collect()
}

pub type Files = Vec<(String, String)>;

/// The base commit: an application that depends on `serde`, which depends on `serde_derive`.
pub fn base() -> Files {
    files(&[
        (
            "Cargo.toml",
            manifest("app", "[dependencies]\nserde = \"1\"\n"),
        ),
        (
            "Cargo.lock",
            lock(&[
                member("app", &["serde"]),
                reg("serde", "1.0.100", 'a').with_deps(&["serde_derive"]),
                reg("serde_derive", "1.0.100", 'b'),
            ]),
        ),
    ])
}

pub fn with(mut list: Files, path: &str, text: &str) -> Files {
    list.retain(|(existing, _)| existing != path);
    list.push((path.to_owned(), text.to_owned()));
    list
}

pub fn side(list: &Files) -> Side {
    Side::of(
        &CargoFormat,
        list.iter().map(|(p, t)| (p.as_str(), t.as_str())),
    )
}

pub fn judge_with(base: &Files, head: &Files, internal: &[String]) -> Integrity {
    let popular = PopularNames::bundled().expect("the bundled list");
    let cx = Context {
        internal_names: internal,
        popular: &popular,
    };
    inspect(&CargoFormat, &side(base), &side(head), &cx).expect("the base is readable")
}

pub fn judge(base: &Files, head: &Files) -> Integrity {
    judge_with(base, head, &[])
}
